CREATE TABLE IF NOT EXISTS kv (k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE IF NOT EXISTS products (id TEXT PRIMARY KEY, created_at INTEGER, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS images (id TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS promos (code TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (uid TEXT PRIMARY KEY, phone TEXT UNIQUE NOT NULL, name TEXT, address TEXT, pass TEXT NOT NULL, created_at INTEGER);
CREATE TABLE IF NOT EXISTS orders (id TEXT PRIMARY KEY, uid TEXT NOT NULL, number TEXT UNIQUE, status TEXT NOT NULL, created_at INTEGER, data TEXT NOT NULL, receipt TEXT);
CREATE INDEX IF NOT EXISTS idx_orders_uid ON orders(uid);
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders(created_at);
CREATE TABLE IF NOT EXISTS rl (k TEXT PRIMARY KEY, n INTEGER, t INTEGER);
